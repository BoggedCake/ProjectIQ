'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),E=require('../commercial-engine.js'),V=require('../voice.js');
assert.ok(fs.existsSync(require('node:path').join(__dirname,'../comparison-engine.js')),'comparison pathway engine is available');
const C=require('../comparison-engine.js');
const base={sale:2000000,purchase:2500000,contractDate:'2026-10-09',sellingPct:.02,marketing:10000,saleLegal:2000,discharge:500,purchaseLegal:3000,searches:500,moving:5000};
const unknown=C.evaluate(base);
assert.equal(unknown.transactionGap,679787);
assert.equal(unknown.costs.transactionCost,179787);
assert.equal(unknown.netSaleEquity,null);
assert.equal(unknown.capitalNeededAfterLoan,null);
assert.equal(unknown.costs.finance,null);
assert.equal(unknown.recommendation.pathway,'verify');
const provided={...base,loanBalance:800000,buildingPest:750,finance:12000,holding:4000,futureProjectCost:100000,keepProjectCost:1200000,keepFinance:25000,keepHolding:15000};
const r=C.evaluate(provided);
assert.equal(r.changeover.duty,E.moveComparison({...base,enabled:true}).duty);
assert.equal(r.netSaleEquity,1147500);
assert.equal(r.capitalNeededAfterLoan,1596537);
assert.equal(r.costs.moveKnownCost,796537);
assert.equal(r.costs.keepKnownCost,1240000);
assert.equal(r.recommendation.pathway,'sell-buy');
assert.match(r.recommendation.summary,/443,463/);
assert.match(r.nextSteps.join(' '),/agent.*loan.*broker.*duty.*planning.*sequence/i);
assert.match(C.evaluate({...provided,replacementType:'site',goal:'duplex'}).replacementCriteria.join(' '),/dual occupancy.*subdivision.*frontage.*overlays/i);
assert.equal(C.evaluate({...provided,keepProjectCost:10000}).recommendation.pathway,'keep');
assert.equal(C.evaluate({...provided,keepGoalFit:true,replacementGoalFit:false}).recommendation.pathway,'keep');
assert.equal(C.evaluate({...provided,futureProjectCost:-1}).status,'review');
assert.equal(C.evaluate({...provided,loanBalance:'bad'}).status,'review');
assert.equal(C.evaluate({...provided,contractDate:'2027-08-01'}).status,'review');
assert.equal(C.evaluate({...provided,loanBalance:0}).netSaleEquity,1947500);
const normal=V.normalizeTranscript('Can I build jewel occupancy at 12 Fishbourne Road?',{confidence:.4});
assert.equal(normal.raw,'Can I build jewel occupancy at 12 Fishbourne Road?');
assert.equal(normal.text,'Can I build dual occupancy at 12 Fishbourne Road?');
assert.equal(normal.lowConfidence,true);
assert.equal(V.normalizeTranscript('I have jewel curtains on Jewel Street',{confidence:.9}).text,'I have jewel curtains on Jewel Street');
assert.equal(V.normalizeTranscript('Can I build dual occupation?').text,'Can I build dual occupancy?');
assert.deepEqual(E.interpretIntent(normal.text),E.interpretIntent('Can I build dual occupancy at 12 Fishbourne Road?'));
assert.equal(V.normalizeTranscript('12 Fisborne Road',{alternatives:['12 Fishbourne Road'],confidence:.2}).text,'12 Fisborne Road');
assert.equal(V.normalizeTranscript('dual occupancy',{confidence:0}).lowConfidence,false);
console.log('PASS comparison costs, equity, actionable pathways and conservative voice/text parity');

assert.notEqual(C.evaluate({...provided,replacementGoalFit:false}).recommendation.pathway,'sell-buy');
assert.notEqual(C.evaluate({...provided,keepProjectCost:10000,keepGoalFit:false}).recommendation.pathway,'keep');
