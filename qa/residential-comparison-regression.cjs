'use strict';
const assert=require('node:assert/strict'),Q=require('../comparison-engine'),E=require('../commercial-engine');
const input={sale:2000000,purchase:2500000,contractDate:'2026-10-09',sellingPct:.02,marketing:10000,saleLegal:2000,discharge:500,purchaseLegal:3000,searches:500,moving:5000,loanBalance:800000,buildingPest:750,finance:12000,holding:4000,futureProjectCost:100000,keepProjectCost:1200000,keepFinance:25000,keepHolding:15000};
const r=Q.evaluate(input),e=E.moveComparison({...input,enabled:true,finance:0});
assert.equal(r.changeover.duty,e.duty,'official duty calculation stays intact');
assert.equal(r.transactionCosts,180537);
assert.equal(r.transactionCosts,e.sellingCosts+e.purchaseCosts+input.buildingPest);
assert.equal(r.availableEquity,1147500);
assert.equal(r.availableEquity,input.sale-e.sellingCosts-input.loanBalance);
assert.equal(r.replacementExpenditure,2744037);
assert.equal(r.totalProjectExpenditure,2796537);
assert.equal(r.replacementFunding,1596537);
assert.equal(r.replacementFunding,input.purchase+e.purchaseCosts+input.buildingPest+input.futureProjectCost+input.finance+input.holding-r.equityApplied);
assert.equal(r.totalProjectExpenditure,input.purchase+r.transactionCosts+input.futureProjectCost+input.finance+input.holding);
assert.equal(r.costs.keepTotalCost,1240000);
const partialEquity=Q.evaluate({...input,equityApplied:1000000});
assert.equal(partialEquity.replacementFunding,1744037);
assert.equal(Q.evaluate({...input,equityApplied:2000000}).status,'review');
const unknownPrincipal=Q.evaluate({...input,loanBalance:undefined});
assert.equal(unknownPrincipal.availableEquity,null);
assert.equal(unknownPrincipal.mortgagePayoutShortfall,null);
assert.equal(unknownPrincipal.equityApplied,null);
assert.equal(unknownPrincipal.replacementFunding,null);
assert.equal(unknownPrincipal.capitalNeededAfterLoan,null);
assert.equal(unknownPrincipal.transactionCosts,r.transactionCosts);
assert.equal(Q.evaluate({...input,finance:undefined}).replacementFunding,null);
assert.equal(Q.evaluate({...input,holding:undefined}).totalProjectExpenditure,null);
assert.equal(Q.evaluate({...input,buildingPest:undefined}).transactionCosts,null);
for(const status of ['mandatory-standard-not-met','prohibited','alternative-pathway-potential','unresolved','not-assessed','requirements-satisfied']){
 const blocked=Q.evaluate({...input,keepGoalFit:true,replacementGoalFit:false,eligibility:{status,readyForFeasibility:false}});
 assert.equal(blocked.keepBaselineAvailable,false,status);
 assert.equal(blocked.costs.keepProjectCost,null,status);
 assert.equal(blocked.costs.keepKnownCost,null,status);
 assert.equal(blocked.costs.keepTotalCost,null,status);
 assert.equal(blocked.comparisonComplete,false,status);
 assert.equal(blocked.costAdvantage,null,status);
 assert.equal(blocked.recommendation.pathway,'verify',status);
 assert.equal(blocked.replacementFunding,r.replacementFunding,status);
}
assert.equal(Q.evaluate({...input,eligibility:{status:'requirements-satisfied',readyForFeasibility:true}}).comparisonComplete,true);
assert.equal(Q.evaluate({...input,loanBalance:0}).availableEquity,1947500);
const underwater=Q.evaluate({...input,loanBalance:2100000});
assert.equal(underwater.availableEquity,-152500);
assert.equal(underwater.mortgagePayoutShortfall,152500);
assert.equal(underwater.equityApplied,0);
assert.equal(underwater.replacementFunding,r.replacementExpenditure+152500);
assert.equal(underwater.capitalNeededAfterLoan,2896537);
assert.equal(underwater.totalProjectExpenditure,r.totalProjectExpenditure,'mortgage principal is funding, not project expenditure');
assert.equal(underwater.transactionCosts,r.transactionCosts,'mortgage principal is not a transaction cost');
assert.equal(underwater.replacementFunding,input.purchase+r.changeover.purchaseCosts+input.buildingPest+input.futureProjectCost+input.finance+input.holding-underwater.availableEquity);
assert.equal(Q.evaluate({...input,keepProjectCost:9999999}).replacementFunding,r.replacementFunding,'current project expenditure never enters replacement funding');
console.log('PASS residential fees, expenditure, equity and funding reconcile; unknown principal and unavailable development baseline stay unknown');
